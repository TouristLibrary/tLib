#!/bin/bash
# Version 1.0 - 19.01.2026
# Скрипт установки TlibWebApp для локального запуска (LAN)
# Устанавливает базовые зависимости без дополнительных сервисов

set -e  # Прервать выполнение при любой ошибке

# Импорт общих функций
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/install_ubuntu_common.sh"

# Установка обработчика ошибок
trap 'handle_error $LINENO' ERR

echo "=================================================="
echo "Установка TlibWebApp (режим: локальный сервер)"
echo "=================================================="

log "1. Обновление системных пакетов..."
sudo apt update
sudo apt upgrade -y

log "2. Проверка и установка Python..."
check_and_install_python

log "3. Создание виртуальной среды..."
create_venv

log "4. Установка зависимостей..."
install_requirements

log "5. Создание директорий..."
create_directories

log "6. Получение IP адреса сервера..."
LOCAL_IP=$(hostname -I | awk '{print $1}')
log "Локальный IP адрес сервера: $LOCAL_IP"

log "=================================================="
log "✓ УСТАНОВКА ЗАВЕРШЕНА УСПЕШНО!"
log "=================================================="
log ""
log "Режим: Локальный сервер (LAN)"
log "Приложение будет доступно в локальной сети без HTTPS"
log ""
log "Для запуска приложения выполните:"
log "  ./start_ubuntu_local.sh"
log ""
log "Приложение будет доступно по адресу:"
log "  http://$LOCAL_IP:8080/"
log ""
log "Для остановки приложения нажмите Ctrl+C"
log "=================================================="

# Создание файла с информацией о развертывании
print_deployment_info "./start_ubuntu_local.sh" "Локальный сервер (LAN)"

log "Информация о развертывании сохранена в deployment_info.txt"
