#!/bin/bash
# Version 1.1 - 03.09.2026
# 1.1 - пауза делается только между попытками, а не после последней:
#       перед перезапуском tailscaled не ждём лишние 10 секунд.
# Watchdog публичной доступности TlibWebApp через Tailscale Funnel.
# Проверяет: 1) отвечает ли приложение локально; 2) доступен ли сайт по
# публичному пути (через собственный DoH, минуя MagicDNS). Если приложение
# живо, а публичный путь молчит — перезапускает tailscaled.
#
# Причина: известный класс багов Tailscale, когда узел меняет "домашний"
# DERP-релей (например, из-за разницы в задержке в 1 мс), но пиры и
# ingress-серверы Funnel продолжают использовать старый релей — трафик
# пропадает, при этом "tailscale funnel status" по-прежнему пишет "on",
# а "tailscale status --json" не показывает никаких Health-предупреждений.
# Обычный curl к публичному имени с самого сервера идёт через MagicDNS на
# адрес tailnet и всегда отвечает 200, поэтому не годится для проверки —
# нужен запрос через публичный DNS (--doh-url), который реально проходит
# через ingress Tailscale.
#
# Запускается таймером tlib-net-watchdog.timer раз в 5 минут.

set -u

PUBLIC_URL="${1:?Использование: $0 <публичный URL для проверки, например https://host.tailnet.ts.net/health>}"

# Если приложение локально не отвечает — это не задача watchdog,
# сетевой уровень тут ни при чём.
if ! curl -sf --max-time 10 -o /dev/null "http://127.0.0.1:8080/health"; then
    exit 0
fi

# Две попытки с паузой — чтобы не реагировать на разовую сетевую заминку.
for attempt in 1 2; do
    if curl -sf --max-time 15 --doh-url https://dns.google/dns-query \
        -o /dev/null "$PUBLIC_URL"; then
        exit 0
    fi
    # Пауза нужна только между попытками — перед перезапуском ждать нечего.
    if [ "$attempt" -eq 1 ]; then
        sleep 10
    fi
done

logger -t tlib-net-watchdog "публичный путь недоступен при живом приложении, перезапуск tailscaled"
systemctl restart tailscaled
