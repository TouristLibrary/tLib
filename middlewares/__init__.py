# Version 1.2 - 30.12.2025 07:48:27 GMT
# Middlewares package для TlibWebApp
# Описание: Пакет содержит все middleware компоненты приложения
# - path_security.py: Детекция Path Traversal атак
# - rate_limit.py: Rate limiting для защиты от DoS атак
# - security_headers.py: Добавление заголовков безопасности
# - http_methods.py: Фильтрация HTTP методов
# - request_id.py: Добавление уникального request_id к каждому запросу
# - data_download.py: Добавление Content-Disposition для файлов
# - traffic_stats.py: Сбор статистики посещений (hits, IP, популярные отчёты)
